-- CuyoTech University SSIS database (MySQL 8 / MariaDB 10.5+)
-- Import:  mysql -u root -p < sql/database.sql
CREATE DATABASE IF NOT EXISTS ssis CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ssis;

DROP TABLE IF EXISTS section, inquiry, notification, password_reset, login_attempt, audit_log, clearance, grade_history, grade, enrolled_subject, subject,
  payment, document_request, enrollment, student, user_account, department;

CREATE TABLE department (
  department_id   INT AUTO_INCREMENT PRIMARY KEY,
  department_name VARCHAR(100) NOT NULL,
  department_code VARCHAR(20)  NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE user_account (
  user_id              INT AUTO_INCREMENT PRIMARY KEY,
  username             VARCHAR(50)  NOT NULL UNIQUE,
  password_hash        VARCHAR(255) NOT NULL,
  role                 ENUM('student','registrar','cashier','depthead','admin') NOT NULL,
  status               ENUM('Active','Disabled') NOT NULL DEFAULT 'Active',
  must_change_password TINYINT(1)   NOT NULL DEFAULT 0,
  full_name            VARCHAR(100) NULL,            -- staff display name (students use student table)
  department_id        INT NULL,                     -- used by department heads
  FOREIGN KEY (department_id) REFERENCES department(department_id)
) ENGINE=InnoDB;

CREATE TABLE student (
  student_id     INT AUTO_INCREMENT PRIMARY KEY,
  user_id        INT NOT NULL UNIQUE,
  department_id  INT NOT NULL,
  student_number VARCHAR(20)  NOT NULL UNIQUE,
  first_name     VARCHAR(50)  NOT NULL,
  last_name      VARCHAR(50)  NOT NULL,
  email          VARCHAR(100) NOT NULL,
  contact_number VARCHAR(20)  NOT NULL,
  program        VARCHAR(100) NOT NULL DEFAULT 'Bachelor of Science in Information Technology',
  section        VARCHAR(20)  NOT NULL DEFAULT 'TBA',
  FOREIGN KEY (user_id)       REFERENCES user_account(user_id),
  FOREIGN KEY (department_id) REFERENCES department(department_id)
) ENGINE=InnoDB;

CREATE TABLE enrollment (
  enrollment_id     INT AUTO_INCREMENT PRIMARY KEY,
  student_id        INT NOT NULL,
  school_year       VARCHAR(20) NOT NULL,
  semester          VARCHAR(20) NOT NULL,
  enrollment_date   DATE NOT NULL,
  enrollment_status ENUM('Pending review','Enrolled','Returned','Dropped','Needs revision') NOT NULL DEFAULT 'Pending review',
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE document_request (
  request_id        INT AUTO_INCREMENT PRIMARY KEY,
  student_id        INT NOT NULL,
  document_type     VARCHAR(100) NOT NULL,
  fee               DECIMAL(10,2) NOT NULL,
  request_date      DATE NOT NULL,
  request_status    ENUM('Pending','Processing','Ready','Released','On hold') NOT NULL DEFAULT 'Pending',
  release_date      DATE NULL,
  verification_code VARCHAR(64) UNIQUE NULL,
  issued_by         INT NULL,
  issued_at         DATETIME NULL,
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
  FOREIGN KEY (issued_by)  REFERENCES user_account(user_id)
) ENGINE=InnoDB;

CREATE TABLE payment (
  payment_id     INT AUTO_INCREMENT PRIMARY KEY,
  student_id     INT NOT NULL,
  enrollment_id  INT NULL DEFAULT NULL,
  request_id     INT NULL DEFAULT NULL,
  processed_by   INT NOT NULL,
  amount         DECIMAL(10,2) NOT NULL,
  payment_date   DATE NOT NULL,
  payment_type   VARCHAR(100) NOT NULL,
  payment_status VARCHAR(20) NOT NULL,
  FOREIGN KEY (student_id)    REFERENCES student(student_id) ON DELETE CASCADE,
  FOREIGN KEY (enrollment_id) REFERENCES enrollment(enrollment_id) ON DELETE SET NULL,
  FOREIGN KEY (request_id)    REFERENCES document_request(request_id) ON DELETE SET NULL,
  FOREIGN KEY (processed_by)  REFERENCES user_account(user_id)
) ENGINE=InnoDB;

-- Extra tables used by the screens in the Figma design --------------------
-- Curriculum load: each subject belongs to one degree program + year level,
-- so a student only sees the subjects of their own program and year.
-- Rooms use the campus buildings: Main Building (3 floors), Bagong Cabuyao Hall / BCH (5 floors),
-- Mayor Etok Building (3 floors).
CREATE TABLE subject (
  subject_id INT AUTO_INCREMENT PRIMARY KEY,
  program    VARCHAR(100) NOT NULL,
  year_level TINYINT      NOT NULL,
  code       VARCHAR(20)  NOT NULL,
  title      VARCHAR(100) NOT NULL,
  schedule   VARCHAR(50)  NOT NULL,
  room       VARCHAR(60)  NOT NULL,
  units      TINYINT      NOT NULL,
  UNIQUE KEY uq_subject (program, code),
  INDEX (program, year_level)
) ENGINE=InnoDB;

-- Class sections, managed by the admin (Create account -> Section dropdown)
CREATE TABLE section (
  section_id   INT AUTO_INCREMENT PRIMARY KEY,
  section_name VARCHAR(20)  NOT NULL UNIQUE,   -- e.g. 'BSN 1A'
  program      VARCHAR(100) NOT NULL,
  year_level   TINYINT      NOT NULL,
  INDEX (program, year_level)
) ENGINE=InnoDB;

CREATE TABLE enrolled_subject (
  enrolled_subject_id INT AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  subject_id INT NOT NULL,
  school_year VARCHAR(20) NOT NULL DEFAULT '2026-2027',
  semester VARCHAR(20) NOT NULL DEFAULT '1st Sem',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_enr_sub (student_id, subject_id, school_year, semester),
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
  FOREIGN KEY (subject_id) REFERENCES subject(subject_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE grade (
  grade_id INT AUTO_INCREMENT PRIMARY KEY,
  student_id INT NOT NULL,
  subject_id INT NOT NULL,
  school_year VARCHAR(20) NOT NULL DEFAULT '2026-2027',
  semester VARCHAR(20) NOT NULL DEFAULT '1st Sem',
  prelim DECIMAL(3,2) NULL,
  midterm DECIMAL(3,2) NULL,
  final_grade DECIMAL(3,2) NULL,
  is_published TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY uq_grade_term (student_id, subject_id, school_year, semester),
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
  FOREIGN KEY (subject_id) REFERENCES subject(subject_id)
) ENGINE=InnoDB;

CREATE TABLE grade_history (
  history_id INT AUTO_INCREMENT PRIMARY KEY,
  grade_id INT NULL,
  student_id INT NOT NULL,
  subject_id INT NOT NULL,
  school_year VARCHAR(20) NOT NULL DEFAULT '2026-2027',
  semester VARCHAR(20) NOT NULL DEFAULT '1st Sem',
  period ENUM('prelim', 'midterm', 'final_grade') NOT NULL,
  old_value DECIMAL(3,2) NULL,
  new_value DECIMAL(3,2) NULL,
  changed_by INT NOT NULL,
  changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE,
  FOREIGN KEY (subject_id) REFERENCES subject(subject_id) ON DELETE CASCADE,
  FOREIGN KEY (changed_by) REFERENCES user_account(user_id)
) ENGINE=InnoDB;

CREATE TABLE clearance (
  clearance_id INT AUTO_INCREMENT PRIMARY KEY,
  student_id   INT NOT NULL,
  office       VARCHAR(30) NOT NULL,
  status       ENUM('Pending','Cleared') NOT NULL DEFAULT 'Pending',
  UNIQUE KEY uq_clear (student_id, office),
  FOREIGN KEY (student_id) REFERENCES student(student_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Security tables (testing plan: audit every record view, rate-limit log in)
CREATE TABLE audit_log (
  log_id     INT AUTO_INCREMENT PRIMARY KEY,
  user_id    INT NULL,
  username   VARCHAR(50) NOT NULL,
  action     VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE login_attempt (
  attempt_id   INT AUTO_INCREMENT PRIMARY KEY,
  username     VARCHAR(50) NOT NULL,
  ip_address   VARCHAR(45) NOT NULL DEFAULT '127.0.0.1',
  attempted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (username, attempted_at),
  INDEX (ip_address, attempted_at)
) ENGINE=InnoDB;

CREATE TABLE password_reset (
  reset_id     INT AUTO_INCREMENT PRIMARY KEY,
  user_id      INT NOT NULL,
  token_hash   VARCHAR(64) NOT NULL,
  expires_at   DATETIME NOT NULL,
  used_at      DATETIME NULL,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES user_account(user_id) ON DELETE CASCADE,
  INDEX (token_hash)
) ENGINE=InnoDB;

CREATE TABLE notification (
  notification_id INT AUTO_INCREMENT PRIMARY KEY,
  user_id         INT NOT NULL,
  title           VARCHAR(255) NOT NULL,
  message         TEXT NOT NULL,
  link            VARCHAR(255) NULL,
  is_read         TINYINT(1) NOT NULL DEFAULT 0,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES user_account(user_id) ON DELETE CASCADE,
  INDEX (user_id, is_read, created_at)
) ENGINE=InnoDB;

CREATE TABLE inquiry (
  inquiry_id     INT AUTO_INCREMENT PRIMARY KEY,
  full_name      VARCHAR(100) NOT NULL,
  student_number VARCHAR(20)  NULL,
  email          VARCHAR(100) NOT NULL,
  concern        VARCHAR(30)  NOT NULL,
  message        TEXT NOT NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

